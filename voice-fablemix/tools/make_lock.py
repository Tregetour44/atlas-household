"""Write requirements.lock for CPython 3.12 win_amd64 from a resolved name==version list, using PyPI's JSON API.

For each pin it picks the one wheel pip would choose on CPython 3.12 / Windows x64, records its sha256 from PyPI's
JSON (digests.sha256) and its size, and fails if a pin has no such wheel. Direct-URL wheels (not on PyPI) are
taken from DIRECT with their pinned hash. Usage: make_lock.py resolved.txt requirements.lock"""
import json
import sys
import urllib.request

# CPython 3.12 x64 Windows tags, most specific first (the order pip prefers).
TAGS = (
    ["cp312-cp312-win_amd64", "cp312-abi3-win_amd64", "cp312-none-win_amd64"]
    + [f"cp3{m}-abi3-win_amd64" for m in range(11, 1, -1)]
    + ["py312-none-win_amd64", "py3-none-win_amd64", "cp312-none-any", "py312-none-any", "py3-none-any", "py2.py3-none-any"]
)
DIRECT = {
    "en-core-web-sm": ("3.8.0", "https://github.com/explosion/spacy-models/releases/download/en_core_web_sm-3.8.0/"
                       "en_core_web_sm-3.8.0-py3-none-any.whl",
                       "1932429db727d4bff3deed6b34cfc05df17794f4a52eeb26cf8928f7c1a0fb85", 12806118),
}


def wheel_tags(filename: str) -> set[str]:
    parts = filename[:-4].split("-")
    py, abi, plat = parts[-3], parts[-2], parts[-1]
    return {f"{p}-{a}-{q}" for p in py.split(".") for a in abi.split(".") for q in plat.split(".")}


def pick(name: str, version: str) -> tuple[str, str, int, str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        files = json.load(r)["urls"]
    best = None
    for f in files:
        if f["packagetype"] != "bdist_wheel" or f.get("yanked"):
            continue
        tags = wheel_tags(f["filename"])
        rank = next((i for i, t in enumerate(TAGS) if t in tags), None)
        if rank is not None and (best is None or rank < best[0]):
            best = (rank, f)
    if best is None:
        raise SystemExit(f"no cp312 win_amd64 wheel for {name}=={version}")
    f = best[1]
    return f["filename"], f["digests"]["sha256"], f["size"], f["url"]


def main() -> None:
    pins = [l.split("==") for l in open(sys.argv[1]).read().split() if "==" in l]
    rows, total = [], 0
    for name, version in sorted(pins, key=lambda p: p[0].lower()):
        key = name.lower().replace("_", "-")
        if key in DIRECT:
            v, url, sha, size = DIRECT[key]
            rows.append(f"en_core_web_sm @ {url} \\\n    --hash=sha256:{sha}\n    # not on PyPI: spaCy's own GitHub release asset, {size} bytes")
        else:
            fn, sha, size, _ = pick(name, version)
            rows.append(f"{name}=={version} \\\n    --hash=sha256:{sha}\n    # {fn}, {size} bytes")
        total += size
        print(rows[-1].splitlines()[-1].strip(), file=sys.stderr)
    head = (f"# Atlas voice-fablemix runtime for CPython 3.12, Windows x64 (win_amd64). {len(rows)} wheels, "
            f"{total:,} bytes ({total / 2**20:.1f} MiB) to download.\n"
            "# Generated by tools/make_lock.py from PyPI's JSON API; every hash is PyPI's digests.sha256.\n"
            "# Install:  py -3.12 -m pip install --require-hashes --no-deps --only-binary :all: -r requirements.lock\n"
            "# Left out on purpose: docopt (num2words' command-line script only; sdist-only, never imported by the\n"
            "#   library), and misaki's [en] extra (spacy-curated-transformers pulls in torch; not used).\n\n")
    open(sys.argv[2], "w", newline="\n").write(head + "\n".join(rows) + "\n")
    print(f"{len(rows)} wheels, {total} bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
