"""Hashed Python requirement files for the two build environments, and a check of an installed env.

  python -I pylock.py write REPORT.json OUT.txt TITLE
      REPORT.json is `pip install --dry-run --ignore-installed --no-deps --report`
      for the pinned set; OUT.txt gets one `name==version --hash=sha256:...` per
      package: the hash of the one artifact (wheel or sdist) pip chose, with its URL.

  python -I pylock.py check ENV_PYTHON REQ.txt [REQ.txt ...] [--allow NAME==VERSION ...]
      The env at ENV_PYTHON must hold exactly the packages and versions in the
      requirement files (plus the --allow entries, e.g. the venv's own pip),
      nothing missing and nothing extra. Exit status 1 on any difference.
"""

import json
import re
import subprocess
import sys


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def write(report_path: str, out_path: str, title: str) -> int:
    report = json.load(open(report_path))
    lines = [f"# {title}", "# Generated by voicepe/tools/pylock.py from a pip install report. Linux x86_64, CPython 3.13.",
             "# One hash per package: the SHA-256 of the exact artifact below. Install with:",
             "#   pip install --no-cache-dir --require-hashes --no-deps --no-build-isolation -r <this file>", ""]
    for item in sorted(report["install"], key=lambda i: norm(i["metadata"]["name"])):
        meta, dl = item["metadata"], item["download_info"]
        sha = dl["archive_info"]["hashes"]["sha256"]
        lines.append(f"# {dl['url']}")
        lines.append(f"{meta['name']}=={meta['version']} \\\n    --hash=sha256:{sha}")
    open(out_path, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(report['install'])} packages")
    return 0


def read_req(path: str) -> dict[str, str]:
    pins = {}
    for line in open(path):
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s\\]+)", line)
        if m:
            pins[norm(m[1])] = m[2]
    return pins


def check(env_python: str, args: list[str]) -> int:
    allow = [a for i, a in enumerate(args) if i and args[i - 1] == "--allow"]
    reqs = [a for i, a in enumerate(args) if a != "--allow" and not (i and args[i - 1] == "--allow")]
    want: dict[str, str] = {}
    for r in reqs:
        want.update(read_req(r))
    for a in allow:
        n, v = a.split("==")
        want[norm(n)] = v
    script = "import json,importlib.metadata as m;print(json.dumps({d.metadata['Name']:d.version for d in m.distributions()}))"
    have = {norm(k): v for k, v in json.loads(subprocess.run([env_python, "-I", "-c", script], check=True,
                                                            capture_output=True, text=True).stdout).items()}
    bad = []
    for n, v in sorted(want.items()):
        if n not in have:
            bad.append(f"missing {n}=={v}")
        elif have[n] != v:
            bad.append(f"wrong version {n}=={have[n]} (lock: {v})")
    bad += [f"not in lock {n}=={have[n]}" for n in sorted(set(have) - set(want))]
    for b in bad:
        print(f"LOCK VIOLATION: {env_python}: {b}", file=sys.stderr)
    print(f"{env_python}: {len(have)} packages, {'matches the lock' if not bad else f'{len(bad)} difference(s)'}")
    return 1 if bad else 0


if __name__ == "__main__":
    if sys.argv[1] == "write":
        sys.exit(write(*sys.argv[2:5]))
    if sys.argv[1] == "check":
        sys.exit(check(sys.argv[2], sys.argv[3:]))
    sys.exit(__doc__)
